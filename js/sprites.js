// On dessine chaque sprite une seule fois dans un petit canvas :
// ensuite, l'afficher ne coûte qu'un drawImage (rapide).
const CACHE_SPRITES = {};
function prerendreSprites() {
  for (const nom in SPRITES) {
    const lignes = SPRITES[nom];
    const c = document.createElement('canvas');
    c.width = lignes[0].length;
    c.height = lignes.length;
    const g = c.getContext('2d');
    lignes.forEach((ligne, y) => {
      [...ligne].forEach((pixel, x) => {
        if (pixel === '.') return;
        g.fillStyle = PALETTE[+pixel];
        g.fillRect(x, y, 1, 1);
      });
    });
    CACHE_SPRITES[nom] = c;
  }
}

function dessinerSprite(ctx, nom, x, y, retourne = false, echelle = 1) {
  const img = CACHE_SPRITES[nom];
  const w = img.width * echelle;
  const h = img.height * echelle;
  x = Math.round(x);
  y = Math.round(y);
  if (retourne) {
    ctx.save();
    ctx.translate(x + w, y);
    ctx.scale(-1, 1);
    ctx.drawImage(img, 0, 0, w, h);
    ctx.restore();
  } else {
    ctx.drawImage(img, x, y, w, h);
  }
}
